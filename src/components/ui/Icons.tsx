import React from "react";

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  size?: number;
  className?: string;
}

/**
 * DirectionalIcon: Mirrors its SVG children when the document or container direction is RTL.
 * Applied via Tailwind `rtl:-scale-x-100` with inline-block transform origin.
 */
export function DirectionalIcon({
  children,
  className = "",
  ...props
}: IconProps & { children: React.ReactNode }) {
  return (
    <span
      className={`inline-flex items-center justify-center rtl:-scale-x-100 transition-transform ${className}`}
      aria-hidden="true"
    >
      {children}
    </span>
  );
}

